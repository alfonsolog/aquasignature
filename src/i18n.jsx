const LangContext = React.createContext({ lang: "en", setLang: () => {}, t: (k) => k });

function LangProvider({ children }) {
  const [lang, setLangState] = React.useState(() => {
    try { return localStorage.getItem("aqua_lang") || "en"; }
    catch (e) { return "en"; }
  });
  const setLang = React.useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem("aqua_lang", l); } catch (e) {}
    document.documentElement.lang = l;
  }, []);
  React.useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = React.useCallback((key) => {
    const v = (DICT[lang] && DICT[lang][key]);
    if (v === undefined) return (DICT.en[key] !== undefined ? DICT.en[key] : key);
    return v;
  }, [lang]);
  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  );
}

function useLang() {
  return React.useContext(LangContext);
}

Object.assign(window, { LangProvider, useLang, DICT });
